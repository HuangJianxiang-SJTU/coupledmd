    print(f"\nMarkdown source: {len(lines)} lines")

    # ── 1: main text + T-tables only ─────────────────────────────────────
    print("\nBuilding manuscript_v1.4.1.docx (main + T1-T3)...")
    doc_main = Document()
    main_stats, figures_main = build_main(doc_main, lines, data, include_si=False)
