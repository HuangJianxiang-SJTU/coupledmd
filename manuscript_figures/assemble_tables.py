def load_all():
    """Return dict meta_key -> (headers, rows, status_str)."""
    result = {}
    for key, meta in TABLE_META.items():
        if meta.get("deferred"):
            result[key] = (None, None, "deferred")
            continue
        fpath = meta.get("file")
        if fpath is None or not Path(fpath).exists():
            result[key] = (None, None, f"missing:{fpath}")
            continue
        h, r = load_csv(fpath)
        if h is None:
            result[key] = (None, None, f"empty:{fpath}")
        else:
            result[key] = (h, r, "ok")
    return result


# ── detection helpers ─────────────────────────────────────────────────────────

def para_inserts_table(text):
    """Return table key if this paragraph should be followed by a table, else None."""
    if "Table T1" in text:
        return "T1"
    if "Table T2" in text:
        return "T2"
    if "Table T3" in text:
        return "T3"
    return None


# ── main build ────────────────────────────────────────────────────────────────

def build_main(doc, lines, data, include_si=False):
    """
    Parse markdown and emit into doc.
    include_si=True appends the SI section after References.
    Returns dict of {table_key: (rows, cols)} for assertions.
    """
    setup_styles(doc)
    for section in doc.sections:
        section.top_margin    = Inches(0.9)
        section.bottom_margin = Inches(0.9)
        section.left_margin   = Inches(0.9)
        section.right_margin  = Inches(0.9)

    mode     = "body"
    fig_buf  = []
    fig_num  = None
    table_stats = {}    # key -> (rows, cols)
    figures_found = []

    def flush_figure():
        nonlocal fig_buf, fig_num
        if fig_num is not None and fig_buf:
            add_figure(doc, fig_num, fig_buf)
            figures_found.append(fig_num)
        fig_buf = []; fig_num = None

    for raw in lines:
        line    = raw.rstrip()
        stripped = line.strip()

        if stripped == "---":
            continue

        # headings
        if line.startswith("## "):
            title = line[3:].strip()
            low = title.lower()
            if low.startswith("figure caption"):
                flush_figure()
                mode = "figures"
                doc.add_heading("Figures", level=1)
                continue
            if low.startswith("reference"):
                flush_figure()
                mode = "references"
                doc.add_heading("References", level=1)
                continue
            flush_figure()
            mode = "body"
            doc.add_heading(title, level=1)
            continue
        if line.startswith("### "):
            doc.add_heading(line[4:].strip(), level=2)
            continue
        if line.startswith("# "):
            p = doc.add_paragraph(style="Title")
            add_runs(p, line[2:].strip())
            continue

        if not stripped:
            continue

        if mode == "figures":
            if stripped.startswith("**Figure"):
                flush_figure()
                fm = re.match(r"\*\*Figure (\d+)\.", stripped)
                fig_num = int(fm.group(1)) if fm else None
                fig_buf = [stripped]
            else:
                fig_buf.append(stripped)
            continue

        if mode == "references":
            p = doc.add_paragraph()
            p.paragraph_format.left_indent       = Inches(0.25)
            p.paragraph_format.first_line_indent = Inches(-0.25)
            p.paragraph_format.space_after       = Pt(3)
            add_runs(p, stripped)
            for r in p.runs: r.font.size = Pt(9)
            continue

        # ordinary body paragraph
        add_runs(doc.add_paragraph(), stripped)

        # insert table after paragraph if referenced
        tkey = para_inserts_table(stripped)
        if tkey and tkey in data:
            h, r, status = data[tkey]
            if status == "ok":
                rc = add_word_table(doc, tkey, h, r)
                table_stats[tkey] = rc
            else:
                p = doc.add_paragraph()
                p.add_run(f"[Table {tkey} — {status}]").italic = True

    flush_figure()

    # ── SI section ──────────────────────────────────────────────────────
    if include_si:
        doc.add_page_break()
        doc.add_heading("Supplementary Information", level=1)
        p = doc.add_paragraph()
        r = p.add_run(
            "CoupledMD: a uniform-protocol molecular dynamics web resource for comparative "
            "analysis of 222 GPCR–G-protein ternary complexes."
        )
        r.bold = True; r.font.size = Pt(10)
        doc.add_paragraph(
            "The following supplementary tables provide the complete per-system data "
            "underlying the analyses reported in the main text. All values are computed "
            "directly from the CoupledMD analysis pipeline; no values have been manually "
            "entered or adjusted. CSV source files are listed in each table caption."
        ).paragraph_format.space_after = Pt(10)

        for skey in ["S1", "S2", "S3", "S4", "S5", "S6", "S7", "S8"]:
            h, r, status = data.get(skey, (None, None, "missing"))
            if status == "ok":
                rc = add_word_table(doc, skey, h, r)
                table_stats[skey] = rc
            else:
                # deferred or missing
                meta = TABLE_META.get(skey, {})
                rc = add_word_table(doc, skey, None, None)
                table_stats[skey] = (0, 0)

    return table_stats, figures_found


def build_si_only(doc, data):
    """Build a standalone SI document with S1-S8."""
    setup_styles(doc)
    for section in doc.sections:
        section.top_margin    = Inches(0.9)
        section.bottom_margin = Inches(0.9)
        section.left_margin   = Inches(0.9)
        section.right_margin  = Inches(0.9)

    # Title block
    p = doc.add_paragraph(style="Title")
    p.add_run("Supplementary Information")
    p2 = doc.add_paragraph()
    r = p2.add_run(
        "CoupledMD: a uniform-protocol molecular dynamics web resource for comparative "
        "analysis of 222 GPCR–G-protein ternary complexes."
    )
    r.bold = True; r.font.size = Pt(11)

    doc.add_paragraph(
        "All tables are computed from the CoupledMD pipeline outputs with no manual "
        "editing. Source CSV files are listed in each table caption. Values marked 'n/a' "
        "indicate data not available for that system; the Gi_8HK2 system reports "
        "length_per_replica_ns = 2 (possible data-entry anomaly — flagged in notes)."
    ).paragraph_format.space_after = Pt(12)

    table_stats = {}
    for skey in ["S1", "S2", "S3", "S4", "S5", "S6", "S7", "S8"]:
        h, r, status = data.get(skey, (None, None, "missing"))
        rc = add_word_table(doc, skey, h if status == "ok" else None,
                                       r if status == "ok" else None)
        table_stats[skey] = rc

    return table_stats


# ── compile check ─────────────────────────────────────────────────────────────

def write_compile_check(main_stats, si_stats, combined_stats, figures_found,
                        data, path):
    lines = [
        "# COMPILE_CHECK.md — Assembly validation report",
        f"Generated by: assemble_tables.py",
        "",
        "## Assertion 1: T1-T3 as native table objects in main docx",
        "",
    ]

    all_pass = True
    for key in ["T1", "T2", "T3"]:
        rc = main_stats.get(key)
        h, r, status = data.get(key, (None, None, "missing"))
        if rc and rc[0] > 0:
            lines.append(f"- **{key}**: PASS — {rc[0]} data rows × {rc[1]} columns  "
                         f"(source: {TABLE_META[key]['file'].name if TABLE_META[key]['file'] else 'n/a'})")
        else:
            lines.append(f"- **{key}**: FAIL — table absent or empty (status: {status})")
            all_pass = False

    lines += [
        "",
        "## Assertion 2: S1-S8 in SI docx (or explicitly marked deferred)",
        "",
    ]
    for key in ["S1", "S2", "S3", "S4", "S5", "S6", "S7", "S8"]:
        rc = si_stats.get(key)
        h, r, status = data.get(key, (None, None, "missing"))
        meta = TABLE_META.get(key, {})
        fpath = meta.get("file")
        if status == "deferred":
            lines.append(f"- **{key}**: PASS (deferred) — placeholder and caption present")
        elif rc and rc[0] > 0:
            fname = Path(fpath).name if fpath else "n/a"
            lines.append(f"- **{key}**: PASS — {rc[0]} data rows × {rc[1]} columns  "
                         f"(source: {fname})")
        else:
            lines.append(f"- **{key}**: FAIL — table absent or empty (status: {status})")
            all_pass = False

    lines += [
        "",
        "## Assertion 3: Figures in combined docx",
        "",
    ]
    for fn in [1, 2, 3, 4, 5]:
        if fn in figures_found:
            lines.append(f"- Figure {fn}: PASS")
        else:
            lines.append(f"- Figure {fn}: FAIL — not found in document")
            all_pass = False

    lines += [
        "",
        "## Table row/column inventory",
        "",
        "| Table | Source file | Data rows | Columns | Status |",
        "|-------|-------------|-----------|---------|--------|",
    ]
    for key in ["T1", "T2", "T3", "S1", "S2", "S3", "S4", "S5", "S6", "S7", "S8"]:
        meta = TABLE_META.get(key, {})
        fpath = meta.get("file")
        fname = Path(fpath).name if fpath else "n/a"
        h, r, status = data.get(key, (None, None, "missing"))
        src_rows = len(r) if r else 0
        src_cols = len(h) if h else 0
        rc = combined_stats.get(key, (0, 0))
        disp_rows, disp_cols = rc
        if status == "deferred":
            lines.append(f"| {key} | n/a | n/a | n/a | deferred |")
        elif status == "ok":
            lines.append(f"| {key} | {fname} | {src_rows} ({disp_rows} displayed) "
                         f"| {src_cols} ({disp_cols} displayed) | ok |")
        else:
            lines.append(f"| {key} | {fname} | n/a | n/a | {status} |")

    lines += [
        "",
        "## Output files",
        "",
    ]
    for fname, desc in [
        ("versions/manuscript_v1.4.1.docx",          "Main text + T1-T3 embedded"),
        ("versions/SI_v1.0.0.docx",                  "Standalone SI with S1-S8"),
        ("versions/manuscript_v1.4.1_combined.docx",  "Combined: main + SI appended"),
    ]:
        fpath = HERE / fname
        if fpath.exists():
            lines.append(f"- **{fname}**: {fpath.stat().st_size:,} bytes — {desc}")
        else:
            lines.append(f"- **{fname}**: MISSING — {desc}")
            all_pass = False

    lines += [
        "",
        f"## Overall: {'✓ ALL ASSERTIONS PASS' if all_pass else '✗ ONE OR MORE ASSERTIONS FAILED'}",
    ]

    Path(path).write_text("\n".join(lines) + "\n", encoding="utf-8")
    return all_pass


