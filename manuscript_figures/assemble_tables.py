    print("\nBuilding manuscript_v1.4.1_combined.docx (main + SI)...")
    doc_comb = Document()
    comb_stats, figures_comb = build_main(doc_comb, lines, data, include_si=True)
    out_comb = VERSIONS / "manuscript_v1.4.1_combined.docx"
    doc_comb.save(str(out_comb))
