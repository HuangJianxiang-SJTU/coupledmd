# ── CSV loader ────────────────────────────────────────────────────────────────

def load_csv(path):
    """Return (headers, rows) or (None, None) if file absent."""
    path = Path(path)
    if not path.exists():
        return None, None
    with open(path, newline="", encoding="utf-8") as f:
        reader = list(csv.reader(f))
    return reader[0], reader[1:]


# ── Word helpers ──────────────────────────────────────────────────────────────

def parse_inline(text):
    out, buf = [], ""
    bold = italic = mono = False
    i = 0
    while i < len(text):
        if text[i:i+2] == "**":
            if buf: out.append((buf, bold, italic, mono)); buf = ""
            bold = not bold; i += 2; continue
        if text[i] == "*":
            if buf: out.append((buf, bold, italic, mono)); buf = ""
            italic = not italic; i += 1; continue
        if text[i] == "`":
            if buf: out.append((buf, bold, italic, mono)); buf = ""
            mono = not mono; i += 1; continue
        buf += text[i]; i += 1
    if buf: out.append((buf, bold, italic, mono))
    return out


def add_runs(paragraph, text):
    for seg, bold, italic, mono in parse_inline(text):
        r = paragraph.add_run(seg)
        r.bold = bold; r.italic = italic
        if mono:
            r.font.name = "Consolas"; r.font.size = Pt(9)
    return paragraph


def setup_styles(doc):
    normal = doc.styles["Normal"]
    normal.font.name = "Arial"; normal.font.size = Pt(10)
    normal.font.color.rgb = INK
    pf = normal.paragraph_format
    pf.space_after = Pt(6); pf.line_spacing = 1.15
    for name, size in [("Heading 1", 13), ("Heading 2", 11), ("Title", 16)]:
        st = doc.styles[name]
        st.font.name = "Arial"; st.font.size = Pt(size)
        st.font.color.rgb = INK; st.font.bold = True


def set_cell_bg(cell, rgb):
    tc = cell._tc
    tcPr = tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    # RGBColor is a tuple subclass; str() returns the hex string e.g. "D9D9D9"
    hex_color = str(rgb)
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), hex_color)
    tcPr.append(shd)


def set_cell_margins(cell, top=0.04, bottom=0.04, left=0.07, right=0.07):
    tc = cell._tc
    tcPr = tc.get_or_add_tcPr()
    tcMar = OxmlElement("w:tcMar")
    for side, val in [("top", top), ("bottom", bottom),
                       ("left", left), ("right", right)]:
        m = OxmlElement(f"w:{side}")
        m.set(qn("w:w"), str(int(val * 1440)))
        m.set(qn("w:type"), "dxa")
        tcMar.append(m)
    tcPr.append(tcMar)


def add_word_table(doc, meta_key, headers, rows):
    """Build a native Word table from metadata + data. Returns (#rows, #cols) tuple."""
    meta  = TABLE_META[meta_key]
    font_size = meta.get("font_size", 9)

    # ── caption ──────────────────────────────────────────────────────────
    cap = doc.add_paragraph()
    cap.paragraph_format.space_before = Pt(10)
    cap.paragraph_format.space_after  = Pt(3)
    cap_text = meta["caption"]
    # bold the "Table Tx." label
    m = re.match(r"^(Table [TS]\d+\.)(.*)", cap_text)
    if m:
        r = cap.add_run(m.group(1)); r.bold = True; r.font.size = Pt(9)
        r2 = cap.add_run(m.group(2)); r2.font.size = Pt(9)
    else:
        r = cap.add_run(cap_text); r.font.size = Pt(9)

    # ── deferred placeholder ──────────────────────────────────────────────
    if meta.get("deferred"):
        p = doc.add_paragraph()
        r = p.add_run("[Table deferred — data not yet available. See caption for planned content.]")
        r.italic = True; r.font.size = Pt(9)
        doc.add_paragraph().paragraph_format.space_after = Pt(4)
        return (0, 0)

    # ── column selection ─────────────────────────────────────────────────
    display_cols    = meta.get("display_cols")
    display_headers = meta.get("display_headers")

    if display_cols is not None:
        show_headers = display_headers
        show_rows    = []
        for row in rows:
            # pad row to avoid index errors on short rows
            padded = row + [""] * max(0, max(display_cols) + 1 - len(row))
            show_rows.append([padded[i] for i in display_cols])
    else:
        show_headers = headers
        show_rows    = rows

    # ── build table ──────────────────────────────────────────────────────
    n_cols = len(show_headers)
    col_widths = meta.get("col_widths")
    if col_widths is None or len(col_widths) != n_cols:
        total = 6.4
        col_widths = [total / n_cols] * n_cols

    tbl = doc.add_table(rows=1 + len(show_rows), cols=n_cols)
    tbl.style = "Table Grid"

    # set column widths
    for ci in range(n_cols):
        for cell in tbl.column_cells(ci):
            cell.width = Inches(col_widths[ci])

    # header row
    hrow = tbl.rows[0]
    for ci, h in enumerate(show_headers):
        cell = hrow.cells[ci]
        set_cell_bg(cell, GRAY_HEADER)
        set_cell_margins(cell)
        p = cell.paragraphs[0]
        r = p.add_run(str(h)); r.bold = True; r.font.size = Pt(font_size)

    # data rows
    for ri, row in enumerate(show_rows):
        wrow = tbl.rows[ri + 1]
        # alternate row shading for readability on large tables
        bg = GRAY_LIGHT if (len(rows) > 20 and ri % 2 == 1) else None
        for ci, val in enumerate(row):
            cell = wrow.cells[ci]
            if bg:
                set_cell_bg(cell, bg)
            set_cell_margins(cell)
            p = cell.paragraphs[0]
            # truncate very long values in display tables
            display_val = str(val) if val not in ("", None) else "n/a"
            if len(display_val) > 120:
                display_val = display_val[:117] + "..."
            r = p.add_run(display_val); r.font.size = Pt(font_size)

    doc.add_paragraph().paragraph_format.space_after = Pt(6)
    return (len(show_rows), n_cols)


def add_figure(doc, num, caption_lines):
    path, width = FIGFILES[num]
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.space_before = Pt(8)
    p.paragraph_format.space_after  = Pt(2)
    p.add_run().add_picture(str(path), width=Inches(width))
    cap = doc.add_paragraph()
    cap.paragraph_format.space_after = Pt(10)
    first = caption_lines[0]
    m = re.match(r"^(\*\*Figure \d+\..*?\*\*)(.*)$", first)
    if m:
        add_runs(cap, m.group(1))
        if m.group(2).strip():
            add_runs(cap, " " + m.group(2).strip())
    else:
        add_runs(cap, first)
    for line in caption_lines[1:]:
        add_runs(cap, " " + line.strip())
    for run in cap.runs:
        run.font.size = Pt(9)


